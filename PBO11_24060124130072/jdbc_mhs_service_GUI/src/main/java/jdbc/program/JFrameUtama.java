    private void refreshList(){
       List<Mahasiswa> listMhs = service.getAll();
       DefaultListModel<String> modelId   = new javax.swing.DefaultListModel<>();
       DefaultListModel<String> modelNama = new javax.swing.DefaultListModel<>();

        for (Mahasiswa mhs : listMhs) {
            modelId.addElement(String.valueOf(mhs.getId()));
            modelNama.addElement(mhs.getNama());
        }

        jListId.setModel(modelId);
        jListNama.setModel(modelNama);
    
    }
    
