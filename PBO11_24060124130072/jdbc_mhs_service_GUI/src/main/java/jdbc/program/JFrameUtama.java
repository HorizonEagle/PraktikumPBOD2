    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        // TODO add your handling code here:
        String idStr   = jTextFieldEditIndex.getText().trim(); // ID yang ingin diedit
        String namaBaru = jTextFieldEditByNama.getText().trim(); // Nama baru

        if (idStr.isEmpty() || namaBaru.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID dan Nama baru harus diisi!");
            return;
        }

        try {
            int id = Integer.parseInt(idStr);
            Mahasiswa mhs = new Mahasiswa(id, namaBaru);
            service.update(mhs);

            refreshList();
            jTextFieldEditByNama.setText("");
            jTextFieldEditIndex.setText("");
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        }
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        // TODO add your handling code here:
         String idStr = jTextFieldDeleteIndex.getText().trim(); 

        if (idStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus diisi!");
            return;
        }

        try {
            int id = Integer.parseInt(idStr);
            service.delete(id);

            refreshList();
            jTextFieldDeleteByNama.setText("");
            jTextFieldDeleteIndex.setText("");
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "ID harus berupa angka!");
        }
    }//GEN-LAST:event_jButtonDeleteActionPerformed

